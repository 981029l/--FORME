const { chromium } = require('../outputs/forme/node_modules/@playwright/test');
const fs = require('fs');
const path = require('path');
const base = process.env.FORME_BASE || 'http://127.0.0.1:3001';
const report = { checkedAt: new Date().toISOString(), base, checks: [], errors: [] };
const check = (name, pass, detail) => { report.checks.push({ name, pass: Boolean(pass), detail }); if (!pass) throw new Error(name + ': ' + JSON.stringify(detail)); };
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => report.errors.push(e.message));
  page.on('response', r => { if(r.status()>=400) report.errors.push(r.status()+' '+r.url()); });
  page.on('console', e => { if (e.type() === 'error') report.errors.push({text:e.text(),location:e.location()}); });
  const goto = async url => { await page.goto(base + url, { waitUntil: 'networkidle' }); };
  const count = n => page.waitForFunction(n => document.querySelectorAll('.library-card').length === n, n);
  const first = () => page.locator('.library-card').first().getAttribute('data-template');
  const run = async (name, fn) => { try { await fn(); } catch (e) { report.checks.push({name: name + ' completed', pass:false, detail:e.message}); } };
  await run('Catalog filtering', async () => {
    await goto('/templates');
    check('First page has 12 of 24', await page.locator('.library-card').count() === 12 && (await page.locator('.library-result-line').innerText()).includes('24'));
    check('Curated starts at depth', await first() === 'depth');
    await page.getByRole('button', {name:'下一页',exact:true}).click();
    await page.waitForURL('**/templates?page=2');
    await page.waitForFunction(()=>document.querySelector('.library-card')?.dataset.template==='product');
    check('Second page has 12 and starts product', await page.locator('.library-card').count() === 12 && await first() === 'product');
    check('Pagination returns focus to result heading', await page.locator('.library-result-line').evaluate(e=>e===document.activeElement));
    await page.locator('#template-search').fill('DEPTH'); await count(1);
    check('Search resets page and finds DEPTH', !page.url().includes('page=') && await first()==='depth');
    await page.reload({waitUntil:'networkidle'});
    check('Reload retains query', await page.locator('#template-search').inputValue()==='DEPTH' && await first()==='depth');
    await page.locator('.library-category-list button').filter({hasText:'产品工具'}).click(); await count(0);
    check('Query and category intersect with empty state', await page.locator('.library-empty').isVisible());
    await page.locator('.library-clear').click(); await count(12);
    await page.locator('.library-sort select').selectOption('name');
    await page.waitForFunction(()=>document.querySelector('.library-card')?.dataset.template==='fashion');
    check('Name sort alphabetical', await first()==='fashion');
    await page.locator('.library-sort select').selectOption('latest');
    await page.waitForFunction(()=>document.querySelector('.library-card')?.dataset.template==='depth');
    check('Latest sort second is doodle', await page.locator('.library-card').nth(1).getAttribute('data-template')==='doodle');
    await page.locator('#template-search').fill('不存在的模板'); await count(0);
    await page.locator('#template-search').press('Escape'); await count(12);
    check('Escape clears query and retains focus', await page.locator('#template-search').inputValue()==='' && await page.locator('#template-search').evaluate(e=>e===document.activeElement));
    await page.getByRole('button',{name:'收藏纵深',exact:true}).click();
    await page.locator('.library-favorites').click(); await count(1);
    check('Favorite filter includes saved template', await first()==='depth' && page.url().includes('view=favorites'));
    await page.reload({waitUntil:'networkidle'}); await count(1);
    check('Favorites persist after reload', await first()==='depth');
    await page.getByRole('button',{name:'取消收藏纵深',exact:true}).click(); await count(0);
    check('Removing last favorite has empty state', await page.locator('.library-empty').isVisible());
    await page.locator('.library-clear').click(); await count(12);
  });
  await run('Quick preview and detail', async () => {
    await goto('/templates');
    const trigger = page.locator('.library-card[data-template="editorial"] .library-quick-open');
    await trigger.click();
    await page.waitForFunction(()=>document.querySelector('dialog')?.open);
    const modal=page.locator('dialog');
    check('Preview one iframe and locked body', await modal.locator('iframe').count()===1 && await page.evaluate(()=>document.body.style.overflow)==='hidden');
    await modal.getByRole('button',{name:'手机',exact:true}).click();
    check('Quick mobile viewport 390', await modal.locator('iframe').evaluate(e=>e.style.width==='390px'));
    await modal.getByRole('button',{name:'桌面',exact:true}).click();
    check('Quick desktop viewport 1440', await modal.locator('iframe').evaluate(e=>e.style.width==='1440px'));
    await modal.locator('iframe').waitFor();
    const frame = await modal.locator('iframe').elementHandle().then(e=>e.contentFrame());
    await frame.waitForLoadState('networkidle'); await frame.locator('body').click({position:{x:200,y:200}}); await page.keyboard.press('Escape');
    await page.waitForFunction(()=>!document.querySelector('dialog'));
    check('Escape in iframe closes and restores focus', await trigger.evaluate(e=>e===document.activeElement) && await page.evaluate(()=>document.body.style.overflow)!=='hidden');
    await trigger.click(); await page.waitForFunction(()=>document.querySelector('dialog')?.open);
    await page.locator('.quick-preview-close').click(); await page.waitForFunction(()=>!document.querySelector('dialog'));
    check('Close button restores focus', await trigger.evaluate(e=>e===document.activeElement));
    await trigger.click(); await page.waitForFunction(()=>document.querySelector('dialog')?.open);
    await page.mouse.click(2,2); await page.waitForFunction(()=>!document.querySelector('dialog'));
    check('Backdrop closes preview', await trigger.evaluate(e=>e===document.activeElement));
    await goto('/templates?sort=latest&page=2');
    await page.locator('.library-card').nth(7).scrollIntoViewIfNeeded();
    const source = page.url(); const y = await page.evaluate(()=>window.scrollY);
    await page.locator('.library-card').nth(7).locator('.library-quick-open').click();
    await page.locator('.quick-preview-detail').click();
    await page.waitForURL('**/templates/*?from=*'); await page.waitForLoadState('networkidle');
    check('Detail carries safe return URL', page.url().includes('from='));
    check('Modal navigation releases body lock', await page.evaluate(()=>document.body.style.overflow)!=='hidden');
    await page.locator('.preview-page-tabs button').nth(1).click();
    check('Detail project tab changes source', (await page.locator('.preview-panel iframe').getAttribute('src')).endsWith('/project'));
    await page.locator('.preview-page-tabs button').nth(2).click();
    check('Detail about tab changes source', (await page.locator('.preview-panel iframe').getAttribute('src')).endsWith('/about'));
    await page.locator('.device-tabs').getByRole('button',{name:'手机',exact:true}).click();
    check('Detail mobile viewport 390', await page.locator('.preview-panel iframe').evaluate(e=>e.style.width==='390px'));
    await page.locator('.back-link').click(); await page.waitForURL(source); await page.waitForLoadState('networkidle');
    await page.locator('.library-card').first().waitFor();
    await page.waitForFunction(y=>Math.abs(window.scrollY-y)<10,y,{timeout:3000});
    const returned = await page.evaluate(()=>window.scrollY);
    check('Custom return restores filter page and scroll', Math.abs(returned-y)<10, {y,returned,url:page.url()});
    await page.locator('.library-card').nth(7).locator('.library-cover a').click(); await page.waitForURL('**/templates/*?from=*');
    await page.goBack({waitUntil:'networkidle'});
    await page.locator('.library-card').first().waitFor();
    await page.waitForFunction(y=>Math.abs(window.scrollY-y)<10,y,{timeout:3000});
    check('Browser Back restores page and scroll', page.url()===source && Math.abs(await page.evaluate(()=>window.scrollY)-y)<10, {y,returned:await page.evaluate(()=>window.scrollY)});
  });
  await run('Legacy and navigation', async () => {
    await goto('/#collection'); await page.waitForURL('**/templates');
    check('Legacy hash opens catalog', new URL(page.url()).pathname==='/templates');
    await goto('/?view=favorites#collection'); await page.waitForURL('**/templates?view=favorites');
    check('Legacy favorites preserved', page.url().includes('templates?view=favorites'));
    await goto('/templates/editorial?from=https://example.com');
    check('Untrusted return rejected', await page.locator('.back-link').getAttribute('href')==='/templates');
    await page.setViewportSize({width:390,height:844}); await goto('/');
    await page.locator('.mobile-menu summary').click();
    check('Mobile menu opens', await page.locator('.mobile-menu').getAttribute('open')!==null);
    await page.locator('.mobile-menu nav').getByRole('link',{name:'模板库',exact:false}).click(); await page.waitForURL('**/templates');
    check('Mobile menu closes on navigation', await page.locator('.mobile-menu').getAttribute('open')===null);
    await page.locator('.theme-toggle').click(); check('Theme light selectable', await page.locator('html').getAttribute('data-theme')==='light');
    await page.locator('.theme-toggle').click(); check('Theme dark selectable', await page.locator('html').getAttribute('data-theme')==='dark');
    await page.locator('.theme-toggle').click(); check('Theme system selectable', await page.locator('html').getAttribute('data-theme')===null);
  });
  await browser.close();
  fs.writeFileSync(path.join(__dirname, 'showroom-flows.json'), JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  if(report.checks.some(x=>!x.pass)||report.errors.length) process.exitCode=1;
})().catch(e=>{console.error(e);process.exitCode=1});
